"""FORK mid-turn machine notices (``agent/interrupt_control.py::push_notice``): a gateway delivery the
session's RUNNING turn takes at its own drain, instead of waiting for that turn to end.

A background-process completion that lands mid-turn used to sit queued for as long as the turn ran
(measured live 2026-10-30: 84 and 22 minutes behind one 90-minute turn), so the model learned about a
finished process only when the turn ended. The delivery seam is /steer's — its own ``role:user`` row,
inserted after the newest tool result — plus the two differences that make it honest: the caller's
display kind/display metadata, and NO out-of-band user marker, because a machine notice must not read as
something the user wrote.

What each guard below fails on without its fix:
- the row's content/shape/kind: a notice routed through ``steer_user_row`` would carry the out-of-band
  user marker and ``display_kind='steer'`` — the model tells the user "you told me X", and the desktop
  paints a user bubble instead of the process card.
- the ticket fates: without them a delivery cannot tell "the turn took it" from "the turn ended first",
  which is the whole difference between settling a row and putting it back in its own FIFO place.
- the no-tool-result path: the notice goes back rather than being dropped or smeared onto a persisted
  row.
"""
import threading

from agent.interrupt_control import InterruptControlMixin
from agent.turn_iteration_prep import _drain_midturn_notices

NOTICE = ("[IMPORTANT: Background process proc_395b7b937e8f completed normally (exit code 0).\n"
          "Command: cd ~/switch2-socket; python3 - <<'PY'\nOutput:\nDONE]\n\n"
          "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user.]")
DISPLAY = {'display_text': 'Background Process Finished: saveswap verify'}


class Agent(InterruptControlMixin):
    """The real notice/steer seams, with the two buffers an initialized agent carries."""

    def __init__(self):
        self._pending_steer, self._pending_steer_lock = None, threading.Lock()
        self._pending_notices, self._pending_notices_lock = None, threading.Lock()


def _messages():
    return [{"role": "user", "content": "go"},
            {"role": "assistant", "content": "", "tool_calls": [{"id": "c1"}]},
            {"role": "tool", "tool_call_id": "c1", "content": "ran"},
            {"role": "assistant", "content": "still working"}]


def _push(agent, ticket="adm-1"):
    return agent.push_notice(NOTICE, display_kind="process_complete", display_metadata=DISPLAY, ticket=ticket)


def test_a_notice_is_delivered_as_its_own_row_after_the_newest_tool_result():
    agent, messages = Agent(), _messages()
    assert _push(agent) is True

    _drain_midturn_notices(agent, messages)

    row = messages[3]
    assert row["role"] == "user"
    assert row["content"] == NOTICE
    assert "OUT-OF-BAND USER MESSAGE" not in row["content"], "a machine notice claims user authority"
    assert row["display_kind"] == "process_complete", "the desktop's process card must survive the injection"
    assert row["display_metadata"] == DISPLAY
    # Delivered into the running turn: the notice is not waiting for a next-turn delivery, and the user
    # did not intervene (nothing about a running turn's course changed because a process finished).
    assert agent._pending_notices == []
    assert agent.withdraw_notice("adm-1") is False
    assert not getattr(agent, "_turn_user_intervened", False)


def test_a_notice_is_delivered_as_its_own_row_not_smeared_onto_the_tool_row():
    """Anchor pin: the tool row is already persisted append-only, so the notice rides its own row."""
    agent, messages = Agent(), _messages()
    _push(agent)
    before = dict(messages[2])

    _drain_midturn_notices(agent, messages)

    assert messages[2] == before
    assert len(messages) == 5 and messages[3]["content"] == NOTICE


def test_a_notice_with_no_tool_result_goes_back_rather_than_being_lost():
    agent, messages = Agent(), [{"role": "user", "content": "go"}]
    _push(agent)

    _drain_midturn_notices(agent, messages)

    assert messages == [{"role": "user", "content": "go"}], "nothing to deliver after"
    # Its ticket reads unconsumed again, so the delivery that pushed it settles undelivered and its row
    # stays queued: at-least-once, never dropped, never delivered twice.
    assert agent.withdraw_notice("adm-1") is True

    delivered = _messages()
    agent.push_notice(NOTICE, display_kind="process_complete", display_metadata=DISPLAY, ticket="adm-1")
    _drain_midturn_notices(agent, delivered)
    assert delivered[3]["content"] == NOTICE


def test_a_steer_ticket_and_a_notice_ticket_never_settle_each_other():
    agent = Agent()
    agent.steer("use the other port", ticket="adm-steer")
    agent.push_notice(NOTICE, display_kind="process_complete", display_metadata=DISPLAY, ticket="adm-notice")

    assert agent.withdraw_notice("adm-steer") is False, "a steer ticket is not a notice ticket"
    assert agent.withdraw_steer("adm-notice") is False, "a notice ticket is not a steer ticket"
    # Both are still buffered: an unknown ticket in one buffer settles nothing in the other.
    assert agent._drain_pending_steer() == "use the other port"
    assert [part[1] for part in agent._drain_pending_notices()] == [NOTICE]


def test_an_empty_notice_is_refused():
    agent = Agent()
    assert agent.push_notice("   ", display_kind="process_complete") is False
    assert not agent._pending_notices
