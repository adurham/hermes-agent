"""FORK: a background-process completion admitted while its session's turn is RUNNING is handed to that
turn as a mid-turn notice, instead of waiting for the turn to end.

Live incident (2026-10-30, session ``local-11f3d55d…``): one turn ran 11:38 -> 13:10, and two completions
(11:44, 12:46) sat ``status='queued'`` behind it for 84 and 22 minutes while the desktop drawer showed
"2 Queued" — the model could not learn that a process it had started was long finished, because a
completion's only delivery was a NEW queued turn.

The transfer is ``prompt.steer_queued``'s, unchanged (``gateway/session_queued_controls.py``): the row
goes ``queued`` -> terminal ``steering`` bound to the running claim's generation and settles with that
claim — taken by a drain of the turn -> ``steered``, never replayed; not taken (the turn ended first) ->
queued again in its own FIFO place and run once as its own turn, exactly as before. So this is a latency
fix, never a delivery change: nothing is lost and nothing is delivered twice.
"""
import asyncio
import threading
from types import SimpleNamespace

import pytest

from agent.interrupt_control import InterruptControlMixin
from gateway import session_automation, session_finite, session_queued_controls
from gateway.session_automation import hand_completion_midturn
from hermes_state_runtime import STEERING, get_session_admission
from tests.gateway.test_prompt_queued_controls import Agent, _ledger, interactive
from tests.gateway.test_session_authority_cancel_settlement import REF, _authority, _submit

NOTICE = ("[IMPORTANT: Background process proc_395b7b937e8f completed normally (exit code 0).\n"
          "Command: cd ~/switch2-socket; python3 - <<'PY'\nOutput:\nDONE]\n\n"
          "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. Do not "
          "treat it as user input.]")
DISPLAY = {'display_text': 'Background Process Finished: saveswap verify'}


class NoticeAgent(InterruptControlMixin):
    """The real steer/notice seam: a drain of the turn takes buffered notices exactly as it takes steers."""

    def __init__(self):
        self._pending_steer, self._pending_steer_lock = None, threading.Lock()
        self._pending_notices, self._pending_notices_lock = None, threading.Lock()

    def clear_interrupt(self, *args, **kwargs):
        return True


async def _drained(authority):
    task = authority.sessions['s'].task
    if task is not None:
        await asyncio.wait_for(task, 30)


def _running_turn(monkeypatch, agent, claimed, release, ran):
    async def execute(authority, ref, row):
        ran.append(row['payload']['text'])
        authority.adopt_agent(ref.session_id, row['generation'], agent)
        claimed.set()
        await asyncio.wait_for(release.wait(), 30)
        return 'done'
    monkeypatch.setattr(session_finite, 'execute_finite_admission', execute)


@pytest.mark.asyncio
@pytest.mark.parametrize('consumed', [True, False])
async def test_a_completion_is_handed_to_the_running_turn_or_keeps_its_own_turn(tmp_path, monkeypatch, consumed):
    db, authority = _authority(tmp_path, monkeypatch)
    interactive(db)
    agent, claimed, release, ran, taken = NoticeAgent(), asyncio.Event(), asyncio.Event(), [], []
    _running_turn(monkeypatch, agent, claimed, release, ran)
    with db:
        await _submit(authority, 'running')
        await asyncio.wait_for(claimed.wait(), 30)
        queued = await _submit(authority, 'completion-notice')
        handed = await session_queued_controls.hand_notice_to_running_claim(
            authority, queued.ref, queued.admission_id, NOTICE,
            display_kind='process_complete', display_metadata=DISPLAY)
        assert handed is True
        # In the running turn's own buffer, with the display kind the card needs, before the turn ends.
        assert [(part[1], part[2], part[3]) for part in agent._pending_notices] == [
            (NOTICE, 'process_complete', DISPLAY)]
        # Terminal ``steering``: outside the queue (never claimable as its own turn) until it settles.
        assert get_session_admission(db, admission_id=queued.admission_id)['outcome'] == STEERING
        if consumed:
            taken.extend(agent._drain_pending_notices())  # the turn's next pre-API-call drain takes it
        else:
            assert agent.withdraw_notice(queued.admission_id) is True  # what the claim's settlement does
            agent.push_notice(NOTICE, display_kind='process_complete', display_metadata=DISPLAY,
                              ticket=queued.admission_id)  # ...put back for the settlement's own run
        release.set()
        await _drained(authority)
    if consumed:
        assert (taken and taken[0][1]) == NOTICE
        assert _ledger(db) == [('running', 'terminal', 'completed'),
                               ('completion-notice', 'terminal', 'steered')]
        assert ran == ['running'], 'a notice the turn took must never also run as its own turn'
    else:
        assert _ledger(db) == [('running', 'terminal', 'completed'),
                               ('completion-notice', 'terminal', 'completed')]
        assert ran == ['running', 'completion-notice'], 'a notice no drain took runs once, as its own turn'
    assert agent._pending_notices in (None, []), 'a settled transfer leaves nothing buffered'


@pytest.mark.asyncio
async def test_an_idle_session_keeps_the_completion_queued(tmp_path, monkeypatch):
    """Nothing is running to hand it to: the row is a normal queued turn and runs when the drain claims it."""
    db, authority = _authority(tmp_path, monkeypatch)
    interactive(db)
    ran = []

    async def execute(_authority, _ref, row):
        ran.append(row['payload']['text'])
        return 'done'
    monkeypatch.setattr(session_finite, 'execute_finite_admission', execute)
    with db:
        queued = await _submit(authority, 'completion-notice')
        handed = await session_queued_controls.hand_notice_to_running_claim(
            authority, queued.ref, queued.admission_id, NOTICE, display_kind='process_complete',
            display_metadata=DISPLAY)
        assert handed is False
        row = get_session_admission(db, admission_id=queued.admission_id)
        assert (row['status'], row['outcome'], row['generation']) == ('queued', None, None)
        await _drained(authority)
    assert _ledger(db) == [('completion-notice', 'terminal', 'completed')]
    assert ran == ['completion-notice']


@pytest.mark.asyncio
async def test_a_turn_with_no_notice_seam_falls_back_to_the_queue(tmp_path, monkeypatch):
    """A running turn whose agent cannot take a mid-turn notice (a surface with no steer seam) is not
    handed anything: the completion keeps today's behaviour and runs as its own turn."""
    db, authority = _authority(tmp_path, monkeypatch)
    interactive(db)
    agent, claimed, release, ran = Agent(), asyncio.Event(), asyncio.Event(), []
    _running_turn(monkeypatch, agent, claimed, release, ran)
    with db:
        await _submit(authority, 'running')
        await asyncio.wait_for(claimed.wait(), 30)
        queued = await _submit(authority, 'completion-notice')
        assert await session_queued_controls.hand_notice_to_running_claim(
            authority, queued.ref, queued.admission_id, NOTICE, display_kind='process_complete',
            display_metadata=DISPLAY) is False
        assert get_session_admission(db, admission_id=queued.admission_id)['status'] == 'queued'
        release.set()
        await _drained(authority)
    assert ran == ['running', 'completion-notice']


@pytest.mark.asyncio
async def test_the_completion_admission_path_hands_the_row_over(tmp_path, monkeypatch):
    """The fix's call site: admitting a COMPLETION hands the row to the session's running turn, while a
    liveness tick keeps its own path (it is a heartbeat admission, not a completion).

    This is the test that fails on the unfixed tree — without the call, the row is admitted and nothing
    hands it to the turn that is already running."""
    _db, _auth = _authority(tmp_path, monkeypatch)
    interactive(_db)
    calls = []

    async def spy(_authority, ref, admission_id, text, *, display_kind, display_metadata=None):
        calls.append((admission_id, text, display_kind, display_metadata))
        return True
    monkeypatch.setattr(session_queued_controls, 'hand_notice_to_running_claim', spy)

    class FakeAuthority:
        def __init__(self):
            self.admitted = []

        async def admit_automation(self, adapter, event, identity, replaces=None):
            self.admitted.append(identity)
            return SimpleNamespace(admission_id='adm-1', ref=REF)
    fake = FakeAuthority()
    runner = SimpleNamespace(_completion_delivery_identity=lambda evt: ('completion', 'proc_1', 1.0))
    event = SimpleNamespace(text=NOTICE, metadata={'display_kind': 'process_complete',
                                                   'display_text': DISPLAY['display_text']})

    await session_automation.admit_process_notice(runner, fake, None, event,
                                                  {'type': 'completion', 'session_id': 'proc_1'})
    assert fake.admitted == ['["completion","proc_1",1.0]']
    assert calls == [('adm-1', NOTICE, 'process_complete', {'display_text': DISPLAY['display_text']})]

    calls.clear()
    await session_automation.admit_process_notice(runner, fake, None, event,
                                                  {'type': 'heartbeat', 'session_id': 'proc_1'})
    assert calls == [], 'a liveness tick is not a completion and is not handed over'


@pytest.mark.asyncio
async def test_the_handoff_reads_the_card_off_the_event_and_never_raises(tmp_path, monkeypatch):
    """The gateway wrapper: text + display kind come from the admitted notice event, and any failure of the
    handoff leaves the row queued rather than propagating into the watcher's delivery path."""
    db, authority = _authority(tmp_path, monkeypatch)
    interactive(db)
    seen = {}

    async def spy(_authority, ref, admission_id, text, *, display_kind, display_metadata=None):
        seen.update(ref=ref, admission_id=admission_id, text=text, display_kind=display_kind,
                    display_metadata=display_metadata)
        return True
    monkeypatch.setattr(session_queued_controls, 'hand_notice_to_running_claim', spy)
    receipt = SimpleNamespace(admission_id='adm-1', ref=REF)
    event = SimpleNamespace(text=NOTICE, metadata={
        'display_kind': 'process_complete', 'display_text': DISPLAY['display_text'],
        'notification_category': 'result', 'gateway_session_key': 'route'})

    assert await hand_completion_midturn(None, authority, receipt, event) is True
    assert seen == {'ref': REF, 'admission_id': 'adm-1', 'text': NOTICE,
                    'display_kind': 'process_complete',
                    'display_metadata': {'display_text': DISPLAY['display_text'],
                                         'notification_category': 'result'}}

    # No card on the event (a plain watch notice): nothing to hand over, and no call.
    seen.clear()
    assert await hand_completion_midturn(None, authority, receipt,
                                         SimpleNamespace(text=NOTICE, metadata={})) is False
    assert seen == {}

    # A raising handoff is swallowed: the row stays queued and the delivery path continues.
    async def boom(*args, **kwargs):
        raise RuntimeError('store died')
    monkeypatch.setattr(session_queued_controls, 'hand_notice_to_running_claim', boom)
    assert await hand_completion_midturn(None, authority, receipt, event) is False
